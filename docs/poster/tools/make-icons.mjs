// Extracts the Lucide icons the poster uses (the same icon set as the app, ISC licence) into assets/icons.js, so the poster
// page can draw them as inline SVG without React. Run: node docs/poster/tools/make-icons.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "../../..")
const iconsDir = path.join(root, "node_modules/lucide-react/dist/esm/icons")

const NAMES = [
  "bus", "train-front", "car-taxi-front", "footprints", "accessibility", "baby", "luggage", "person-standing", "user",
  "map-pin", "navigation", "route", "search", "shield-check", "sparkles", "brain", "dna", "gauge", "clock", "cloud-rain",
  "users", "volume-2", "star", "message-square", "database", "server", "monitor-smartphone", "globe", "lock", "list-checks",
  "circle-x", "circle-check", "ban", "filter", "git-fork", "layers", "chart-column", "timer", "sun", "map", "smartphone",
  "refresh-cw", "triangle-alert", "heart-pulse", "arrow-right", "check", "x", "scale", "trophy", "test-tube-diagonal",
  "leaf", "wallet", "flag", "locate-fixed", "info", "qr-code", "github",
]

const out = {}
for (const name of NAMES) {
  const file = path.join(iconsDir, `${name}.mjs`)
  if (!fs.existsSync(file)) { console.warn("missing icon:", name); continue }
  const src = fs.readFileSync(file, "utf8")
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/)
  if (!m) { console.warn("no iconNode in", name); continue }
  const nodes = Function(`return ${m[1]}`)()
  out[name] = nodes
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`)
    .join("")
}
const js = `// Generated by tools/make-icons.mjs from lucide-react (ISC licence). Do not edit.\nwindow.ICONS = ${JSON.stringify(out, null, 0)}\n`
fs.writeFileSync(path.join(here, "../assets/icons.js"), js)
console.log(`wrote ${Object.keys(out).length} icons`)
